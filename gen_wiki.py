"""Turn research/divyadesam-wiki-pack.json into src/wiki.js and img/*.jpg.  python3 gen_wiki.py <pack.json>"""
import json,re,sys,base64,pathlib,html
d=json.load(open(sys.argv[1],encoding='utf8'))
root=pathlib.Path(__file__).parent; (root/'img').mkdir(exist_ok=True)
def clean(v):
    v=re.sub(r'<ref[^>]*?/>|<ref.*?</ref>','',v,flags=re.S)
    v=re.sub(r'\{\{(?:convert|cvt)\|([^|}]+)\|([^|}]+)[^}]*\}\}',r'\1 \2',v)
    v=re.sub(r'\{\{(?:lang|transl|IAST)[^|}]*\|(?:[a-z-]+\|)?([^}]+)\}\}',r'\1',v)
    v=re.sub(r'\{\{(?:Plainlist|plainlist|ubl|Unbulleted list|hlist)\s*\|?',' ',v)
    v=re.sub(r'\{\{[^{}]*\}\}','',v); v=v.replace('}}','')
    v=re.sub(r'\[\[(?:[^|\]]*\|)?([^\]]+)\]\]',r'\1',v)
    v=re.sub(r"'{2,}",'',v); v=re.sub(r'<br\s*/?>',', ',v); v=re.sub(r'<[^>]+>','',v)
    v=re.sub(r'\s*\n\s*\*\s*','; ',v); v=re.sub(r'\s+',' ',v).strip(' ;,|')
    return html.unescape(v)[:220]
def infobox(w):
    out={}
    m=re.search(r'\{\{Infobox',w)
    if not m: return out
    body=w[m.start():]
    for k in ('tower','temple_tank','facade_direction','festival','festivals','creator','website','architecture','deity','inscriptions','temple_quantity'):
        mm=re.search(r'^\s*\|\s*'+k+r'\s*=\s*(.*?)(?=^\s*\|\s*[A-Za-z_0-9 ]+=|^\}\})',body,flags=re.M|re.S)
        if mm:
            v=clean(mm.group(1))
            if k=='website':
                u=re.search(r'https?://[^\s|\]}]+',mm.group(1)); v=u.group(0) if u else ''
            if v and v.lower() not in ('yes','no','unknown'): out[k]=v
    return out
def trim(t,n):
    t=re.sub(r'\s+',' ',t).strip()
    if len(t)<=n: return t
    cut=t[:n]; i=max(cut.rfind('. '),cut.rfind('.) '))
    return cut[:i+1] if i>n*0.5 else cut.rsplit(' ',1)[0]+'…'
W={};credits=[];subcount={}
for r in d['rows']:
    n=r['n']; key=f"{n:03d}"
    if r['sub']:
        subcount[n]=subcount.get(n,0)+1; key+='abc'[subcount[n]-1]
    img=d['imgs'].get(r['file']); inf=d['info'].get(r['file'],{})
    if img:
        (root/'img'/f'{key}.jpg').write_bytes(base64.b64decode(img.split(',',1)[1]))
    if r['sub']:
        W[n].setdefault('more',[]).append({'k':key,'name':r['name'].split(' Thanjavur')[0].split(' Thirunagari,')[0][:40],'a':inf.get('artist',''),'l':inf.get('lic',''),'p':inf.get('page','')})
        continue
    ib=infobox(d['wt'].get(r['title'],'')) if r['title'] else {}
    e={'t':r['title'] if r['title'] and 'redlink' not in r['title'] else '', 'd':trim(r['desc'],700), 'x':trim(d['ex'].get(r['title'],''),1100)}
    if r['geo']:
        la,lo=r['geo'].split(';'); e['la']=round(float(la),4); e['lo']=round(float(lo),4)
    for a,b in (('tower','tw'),('temple_tank','tk'),('facade_direction','fd'),('festival','fs'),('festivals','fs'),('creator','cr'),('website','ws'),('inscriptions','ins')):
        if ib.get(a): e[b]=ib[a]
    e['ia']=inf.get('artist','') ; e['il']=inf.get('lic',''); e['ip']=inf.get('page','')
    W[n]=e
(root/'src'/'wiki.js').write_text('/* Generated by gen_wiki.py from Wikipedia and Wikimedia Commons (text CC BY-SA 4.0; photo credits per entry). Do not edit by hand. */\nconst WIKI = '+json.dumps(W,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf8')
print(len(W),'entries', sum(1 for e in W.values() if 'la' in e),'coords', len(list((root/'img').glob('*.jpg'))),'images')
for k in ('tw','tk','fd','fs','cr','ws'): print(k,sum(1 for e in W.values() if k in e))
json.dump(W,open(root/'wiki_tmp.json','w'),ensure_ascii=False)
